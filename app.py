def keyword_correction(text, predicted_emotion):
    if predicted_emotion != "기쁨":
        return predicted_emotion

    for emotion, keywords in negative_keyword_emotion.items():
        for keyword in keywords:
            if keyword in text:
                return emotion

    return predicted_emotion


