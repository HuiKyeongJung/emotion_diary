def has_weather_keyword(text):
    lowered = text.lower()
    return any(keyword in lowered for keyword in weather_keywords)


def get_positive_message(text, emotion):
    if emotion in weather_messages and has_weather_keyword(text):
        return random.choice(weather_messages[emotion])

    message_list = positive_messages.get(emotion, [])
    return (
        random.choice(message_list)
        if message_list
        else "오늘의 감정을 천천히 기록해보세요."
    )


class DiaryRequest(BaseModel):
    text: str


@app.get("/", response_class=HTMLResponse)
def home(request: Request):
    return templates.TemplateResponse(
        "index.html",
        {"request": request},
    )


@app.post("/predict")
def predict(request: DiaryRequest):
    text_vector = vectorizer.transform([request.text])
    emotion = model.predict(text_vector)[0]
    emotion = keyword_correction(request.text, emotion)

    min_score, max_score = emotion_score_range.get(emotion, (40, 60))
    score = random.randint(min_score, max_score)

    positive_message = get_positive_message(request.text, emotion)

    return {
        "input_text": request.text,
        "emotion": emotion,
        "score": score,
        "positive_message": positive_message,
    }
